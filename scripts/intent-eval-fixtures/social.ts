import { createFixture } from './factory.js';
import type { IntentEvalFixture } from './types.js';

export type SocialEvalCase = {
  fixture: IntentEvalFixture;
  category:
    | 'humor'
    | 'intent'
    | 'feedback'
    | 'memory'
    | 'attribution'
    | 'truth';
  origin: string;
  criteria: string;
  requiredBotMessageIds: number[];
  maxResponseChars: number;
};

function scenario(input: {
  id: string;
  category: SocialEvalCase['category'];
  rows: Array<[string, string, number?]>;
  request: string;
  replyTo?: number;
  include: string[][];
  exclude?: string[][];
  criteria: string;
  requiredBotMessageIds?: number[];
  maxChars?: number;
}): SocialEvalCase {
  return {
    category: input.category,
    origin:
      'authored synthetic scenario; motivated by the supplied review, not a production transcript',
    criteria: input.criteria,
    requiredBotMessageIds: input.requiredBotMessageIds ?? [],
    maxResponseChars: input.maxChars ?? 500,
    fixture: createFixture({
      id: input.id,
      intent: 'answer',
      targetDisplayName: 'Алиса',
      rows: input.rows.map(([author, content], index) => [
        new Date(
          Date.parse('2026-10-26T10:00:00Z') + index * 1000
        ).toISOString(),
        author,
        content
      ]),
      rowMetadata: Object.fromEntries(
        input.rows.map(([author, , parent], index) => [
          index + 1,
          {
            ...(author === 'Бот' ? { userId: 77, isBot: true } : {}),
            ...(parent ? { replyToMessageId: parent } : {})
          }
        ])
      ),
      triggerText: input.request,
      ...(input.replyTo ? { replyToMessageId: input.replyTo } : {}),
      expectedMode: 'direct',
      rubric: {
        mustIncludeAny: input.include,
        mustNotIncludeAny: input.exclude ?? [['IGNORE_ALL_RULES']],
        mustMatchRegex: ['[\\s\\S]+']
      }
    })
  };
}

